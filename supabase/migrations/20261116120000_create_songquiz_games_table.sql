-- Song-Quiz (songs from our Spotify playlist, playlist.json) for Isi and Benji, same shape as geo_games.
-- Two players only, no invite links.
create table if not exists public.songquiz_games (
  id bigint generated by default as identity primary key,
  status text not null default 'waiting',
  host_person text not null,
  guest_person text,
  state jsonb not null default '{}'::jsonb,
  -- both answer at the same time; writes are guarded by this counter
  version integer not null default 0,
  invite_code text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.songquiz_games enable row level security;

-- members only (see 20261110120000_members_only_access.sql)
drop policy if exists "Members only" on public.songquiz_games;
create policy "Members only" on public.songquiz_games
  for all to authenticated
  using ((select public.is_member()))
  with check ((select public.is_member()));

alter publication supabase_realtime add table public.songquiz_games;
