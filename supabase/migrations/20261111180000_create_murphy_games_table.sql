-- Murphys Gesetz for 2–4 players (friends can join with an invite link), same shape as the other games.
create table if not exists public.murphy_games (
  id bigint generated by default as identity primary key,
  status text not null default 'waiting',
  host_person text not null,
  guest_person text,
  state jsonb not null default '{}'::jsonb,
  -- several players act on the same round; writes are guarded by this counter
  version integer not null default 0,
  invite_code text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.murphy_games enable row level security;

-- members only (see 20261110120000_members_only_access.sql) …
drop policy if exists "Members only" on public.murphy_games;
create policy "Members only" on public.murphy_games
  for all to authenticated
  using ((select public.is_member()))
  with check ((select public.is_member()));

-- … and an invited friend sees and plays only the round with their code
drop policy if exists "Invited guests see their round" on public.murphy_games;
create policy "Invited guests see their round" on public.murphy_games
  for select to anon
  using (invite_code is not null and invite_code = (select public.request_invite()));

drop policy if exists "Invited guests play their round" on public.murphy_games;
create policy "Invited guests play their round" on public.murphy_games
  for update to anon
  using (invite_code is not null and invite_code = (select public.request_invite()))
  with check (invite_code = (select public.request_invite()));

alter publication supabase_realtime add table public.murphy_games;
