create table if not exists public.geo_games (
  id bigint generated by default as identity primary key,
  status text not null default 'waiting',
  host_person text not null,
  guest_person text,
  state jsonb not null default '{}'::jsonb,
  -- both pick at the same time; writes are guarded by this counter
  version integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.geo_games enable row level security;

create policy "Allow everyone to read"
  on public.geo_games for select
  using (true);

create policy "Allow everyone to insert"
  on public.geo_games for insert
  with check (true);

create policy "Allow everyone to update"
  on public.geo_games for update
  using (true)
  with check (true);

create policy "Allow everyone to delete"
  on public.geo_games for delete
  using (true);

alter publication supabase_realtime add table public.geo_games;
