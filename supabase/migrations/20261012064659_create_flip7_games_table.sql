-- Flip 7 for 2–4 players (friends can join with an invite link), same shape as the other games.
create table if not exists public.flip7_games (
  id bigint generated by default as identity primary key,
  status text not null default 'waiting',
  host_person text not null,
  guest_person text,
  state jsonb not null default '{}'::jsonb,
  -- several players act on the same round; writes are guarded by this counter
  version integer not null default 0,
  invite_code text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.flip7_games enable row level security;

drop policy if exists "Allow everyone to read" on public.flip7_games;
create policy "Allow everyone to read"
  on public.flip7_games for select
  using (true);

drop policy if exists "Allow everyone to insert" on public.flip7_games;
create policy "Allow everyone to insert"
  on public.flip7_games for insert
  with check (true);

drop policy if exists "Allow everyone to update" on public.flip7_games;
create policy "Allow everyone to update"
  on public.flip7_games for update
  using (true)
  with check (true);

drop policy if exists "Allow everyone to delete" on public.flip7_games;
create policy "Allow everyone to delete"
  on public.flip7_games for delete
  using (true);

alter publication supabase_realtime add table public.flip7_games;
